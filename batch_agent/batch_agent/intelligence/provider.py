"""
Intelligence and LLM providers for the autonomous batch agent.
Includes native Zero-Dependency HTTP clients for Gemini, OpenAI, Ollama,
plus a built-in Heuristic Autonomous Provider for air-gapped/offline batch clusters.
"""

from __future__ import annotations

import json
import os
import re
import sys
import urllib.error
import urllib.request
from abc import ABC, abstractmethod
from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional

from batch_agent.config import BatchAgentConfig, LLMProviderType
from batch_agent.intelligence.cot_engine import ChainOfThoughtEngine, ChainOfThoughtRecord
from batch_agent.intelligence.planner import ExecutionPlan, PlanStep, StepStatus


@dataclass
class AgentDecision:
    """Decision output generated by an intelligence provider for a batch step."""
    thought: ChainOfThoughtRecord
    tool_name: Optional[str] = None
    tool_params: Dict[str, Any] = field(default_factory=dict)
    is_finish: bool = False
    finish_summary: str = ""
    tokens_used: Optional[int] = None


class BaseProvider(ABC):
    """Abstract interface for decision-making backends."""

    @abstractmethod
    def decide_next_step(
        self,
        config: BatchAgentConfig,
        plan: ExecutionPlan,
        step_number: int,
        observation: str,
        last_error: Optional[str] = None,
        workspace_files: Optional[List[str]] = None,
    ) -> AgentDecision:
        """Produce the next autonomous decision, reasoning, and tool call."""
        pass


class HeuristicAutonomousProvider(BaseProvider):
    """
    Intelligent heuristic planning and self-correction engine.
    Allows YoYo to operate autonomously in offline, air-gapped batch HPC nodes
    without requiring external internet access or LLM API keys.
    """

    def __init__(self) -> None:
        self._inspected_files: set[str] = set()
        self._initial_plan_built = False

    def build_initial_plan(self, config: BatchAgentConfig, plan: ExecutionPlan) -> None:
        goal_lower = config.goal.lower()

        # Step 1: Ingest and inspect associated files or research papers / SRS docs
        doc_exts = (".pdf", ".tex", ".latex", ".rst")
        doc_keys = ("srs", "paper", "spec", "requirement", "prd", "rfc")
        tech_docs = [
            f for f in config.associated_files
            if os.path.splitext(f.lower())[1] in doc_exts or any(k in f.lower() for k in doc_keys)
        ]

        if tech_docs:
            plan.add_step(
                title=f"Ingest Technical Specification ({os.path.basename(tech_docs[0])})",
                description=f"Parse requirements, algorithms, and architecture from: {', '.join(tech_docs)}",
                action_type="inspect",
                tool_hint="ingest_document",
            )
        elif config.associated_files:
            plan.add_step(
                title="Inspect Associated Input Files",
                description=f"Read and inspect contents of: {', '.join(config.associated_files)}",
                action_type="inspect",
                tool_hint="file_read",
            )
        else:
            plan.add_step(
                title="Scan Workspace Structure",
                description="List directory structure to discover code and assets.",
                action_type="inspect",
                tool_hint="file_list",
            )

        # Step 2: Test discovery or baseline verification
        plan.add_step(
            title="Baseline Verification",
            description="Run initial verification checks to identify existing issues or baseline tests.",
            action_type="verify",
            tool_hint="verify_code",
        )

        # Step 3: Implement modifications / task execution
        plan.add_step(
            title="Execute Primary Objective",
            description=f"Perform modifications and compute operations to satisfy goal: {config.goal}",
            action_type="execute",
            tool_hint="run_command",
        )

        # Step 4: Final verification and validation
        plan.add_step(
            title="Comprehensive Self-Verification",
            description="Run full test suite and validation checks to verify no regressions.",
            action_type="verify",
            tool_hint="verify_code",
        )

        # Step 5: Generate output summary report
        plan.add_step(
            title="Generate Batch Summary Artifact",
            description="Compile final completion report and persist audit artifacts.",
            action_type="report",
            tool_hint="file_write",
        )

        self._initial_plan_built = True

    def decide_next_step(
        self,
        config: BatchAgentConfig,
        plan: ExecutionPlan,
        step_number: int,
        observation: str,
        last_error: Optional[str] = None,
        workspace_files: Optional[List[str]] = None,
    ) -> AgentDecision:
        if not self._initial_plan_built:
            if not plan.steps:
                self.build_initial_plan(config, plan)
            self._initial_plan_built = True

        # Check if all steps in plan are completed
        current = plan.current_step
        if not current or plan.is_finished or plan.all_completed:
            # Goal Fulfillment Check: Ensure primary goal requirements are truly satisfied before terminating
            test_file = os.path.join(config.workspace_root, "proposal", "test_solution.py")
            has_unverified_tests = os.path.exists(test_file) and not any(
                s.action_type == "verify" and s.status == StepStatus.COMPLETED for s in plan.steps
            )

            if has_unverified_tests and config.goal_supremacy:
                # Dynamically mutate plan to verify goal fulfillment rather than terminating prematurely
                v_step = plan.add_step(
                    title="Validate Goal Fulfillment with Test Suite",
                    description=f"Run verification suite to confirm goal '{config.goal}' is achieved.",
                    action_type="verify",
                    tool_hint="verify_code",
                )
                plan.record_mutation(
                    mutation_type="GOAL_VERIFICATION_REPLAN",
                    reason=f"Goal priority mandate: verifying solution before completion for goal: {config.goal}",
                    details={"added_step_id": v_step.id, "title": v_step.title},
                )
                current = v_step
            else:
                thought = ChainOfThoughtEngine.create_thought(
                    phase="FINALIZATION",
                    goal_analysis=f"Primary goal '{config.goal}' successfully accomplished across {len(plan.steps)} planned subgoals.",
                    observation=f"Workspace verified. Latest observation: {observation[:200]}",
                    decision="Mark batch job as completed successfully.",
                    expected_outcome="Graceful batch job completion with zero exit code.",
                    goal_priority=f"Primary Goal: '{config.goal}' accomplished.",
                )
                return AgentDecision(
                    thought=thought,
                    is_finish=True,
                    finish_summary=f"YoYo successfully achieved primary goal: '{config.goal}' across {step_number} steps.",
                )

        # If last action had an error, handle goal-oriented self-correction and plan adaptation
        if last_error:
            current.mark_failed(last_error)
            if current.retry_count >= 2 and config.goal_supremacy:
                # Autonomous plan mutation: change the plan to achieve the goal despite the blocker!
                plan.record_mutation(
                    mutation_type="DYNAMIC_ADAPTATION",
                    reason=f"Step '{current.title}' blocked ({last_error[:80]}). Mutating plan to achieve primary goal: {config.goal}",
                    details={"failed_step_id": current.id, "error": last_error},
                )
                # If plan.txt exists in workspace, sync it
                plan_file_path = os.path.join(config.workspace_root, "plan.txt")
                if os.path.exists(plan_file_path):
                    try:
                        from batch_agent.intelligence.dependency_planner import DependencyPlanner
                        DependencyPlanner.update_plan_file(
                            plan_path=plan_file_path,
                            plan=plan,
                            mutation_reason=f"Adapted plan after error in {current.title}",
                        )
                    except Exception:
                        pass

            thought = ChainOfThoughtEngine.create_thought(
                phase="SELF_CORRECTION",
                goal_analysis=f"Subgoal '{current.title}' encountered failure: {last_error[:150]}",
                observation=f"Attempt {current.retry_count} of {current.max_retries}. Analyzing error output.",
                hypotheses=[
                    "File syntax or parameter mismatch",
                    "Missing directory or dependency",
                    "Subprocess returned non-zero exit code",
                ],
                tradeoffs=[
                    "Retry same command vs apply fallback patch first",
                    "Inspect file contents to locate specific error line",
                ],
                decision=f"Perform diagnosis and attempt corrective action for {current.title}.",
                expected_outcome="Resolve runtime defect and restore execution path.",
                goal_priority=f"Prioritizing primary goal: {config.goal}",
            )
            # Formulate corrective tool
            if current.action_type in ("verify", "execute") and config.associated_files:
                target_file = config.associated_files[0]
                return AgentDecision(
                    thought=thought,
                    tool_name="file_read",
                    tool_params={"path": target_file},
                )

        current.mark_in_progress()

        # Decide tool action based on current step
        if current.action_type == "inspect":
            uninspected = [f for f in config.associated_files if f not in self._inspected_files]
            if uninspected:
                target_file = uninspected[0]
                self._inspected_files.add(target_file)
                # Check if this file is a research paper or specification document
                is_doc = (
                    os.path.splitext(target_file.lower())[1] in (".pdf", ".tex", ".rst")
                    or any(k in target_file.lower() for k in ("srs", "paper", "spec", "requirement", "prd", "rfc"))
                )
                tool_to_use = "ingest_document" if is_doc else "file_read"

                thought = ChainOfThoughtEngine.create_thought(
                    phase="INSPECTION",
                    goal_analysis=f"Need full context of input file '{target_file}' to plan modifications.",
                    observation=f"File '{target_file}' listed in job inputs. Unread.",
                    decision=f"Invoke {tool_to_use} on '{target_file}'.",
                    expected_outcome=f"Acquire file contents and specifications to plan execution.",
                    goal_priority=f"Prioritizing primary goal: {config.goal}",
                )
                return AgentDecision(
                    thought=thought,
                    tool_name=tool_to_use,
                    tool_params={"path": target_file},
                )
            else:
                thought = ChainOfThoughtEngine.create_thought(
                    phase="INSPECTION",
                    goal_analysis="Discover workspace structure.",
                    observation="Associated files inspected. Checking directory tree.",
                    decision="Invoke file_list to survey workspace.",
                )
                return AgentDecision(
                    thought=thought,
                    tool_name="file_list",
                    tool_params={"recursive": False},
                )

        elif current.action_type == "verify":
            target_test = "tests"
            proposal_test = os.path.join(config.workspace_root, "proposal", "test_solution.py")
            if os.path.exists(proposal_test):
                target_test = "proposal/test_solution.py"

            thought = ChainOfThoughtEngine.create_thought(
                phase="VERIFICATION",
                goal_analysis="Verify codebase stability and test suite status non-interactively.",
                observation=f"Current step is verification: {current.title}",
                decision=f"Run code verification check targeting '{target_test}'.",
                expected_outcome="Confirm syntax correctness and test assertions.",
            )
            return AgentDecision(
                thought=thought,
                tool_name="verify_code",
                tool_params={"mode": "unittest", "target": target_test},
            )

        elif current.action_type == "report":
            summary_content = (
                f"# Batch Execution Completion Report\n\n"
                f"- **Job ID**: {config.job_id}\n"
                f"- **Goal**: {config.goal}\n"
                f"- **Status**: COMPLETED\n"
                f"- **Total Steps**: {step_number}\n\n"
                f"## Subgoals Executed:\n{plan.format_summary()}\n"
            )
            thought = ChainOfThoughtEngine.create_thought(
                phase="REPORTING",
                goal_analysis="Persist final batch execution report to workspace.",
                observation="All operational subgoals executed. Writing batch summary artifact.",
                decision="Invoke file_write to generate 'batch_summary.md'.",
                expected_outcome="Artifact written to workspace root.",
            )
            return AgentDecision(
                thought=thought,
                tool_name="file_write",
                tool_params={"path": "batch_summary.md", "content": summary_content},
            )

        else:
            # Default fallback command execution
            proposal_solution = os.path.join(config.workspace_root, "proposal", "solution.py")
            if os.path.exists(proposal_solution):
                exec_cmd = "python3 proposal/solution.py"
            else:
                exec_cmd = "python3 -m unittest discover tests || true"

            thought = ChainOfThoughtEngine.create_thought(
                phase="EXECUTION",
                goal_analysis=f"Execute action for subgoal: {current.title}",
                observation=f"Proceeding with planned step {current.id}.",
                decision=f"Execute non-interactive command: '{exec_cmd}'.",
            )
            return AgentDecision(
                thought=thought,
                tool_name="run_command",
                tool_params={"command": exec_cmd},
            )


class GeminiProvider(BaseProvider):
    """Zero-dependency HTTP client for Google Gemini LLM API."""

    def __init__(self, api_key: Optional[str] = None, model: str = "gemini-3.1-flash-lite") -> None:
        self.api_key = api_key or os.environ.get("GEMINI_API_KEY", "")
        self.model = model
        self.fallback = HeuristicAutonomousProvider()

    def decide_next_step(
        self,
        config: BatchAgentConfig,
        plan: ExecutionPlan,
        step_number: int,
        observation: str,
        last_error: Optional[str] = None,
        workspace_files: Optional[List[str]] = None,
    ) -> AgentDecision:
        if not self.api_key:
            # Gracefully fallback to autonomous heuristic provider
            return self.fallback.decide_next_step(config, plan, step_number, observation, last_error, workspace_files)

        url = f"https://generativelanguage.googleapis.com/v1beta/models/{self.model}:generateContent?key={self.api_key}"

        prompt = (
            f"You are YoYo, an autonomous agentic AI operating in a NON-INTERACTIVE BATCH OS.\n"
            f"PRIMARY GOAL (TOP PRIORITY): {config.goal}\n"
            f"Plan Status:\n{plan.format_summary()}\n"
            f"Associated Files: {config.associated_files}\n"
            f"Current Step: {step_number}\n"
            f"Latest Observation: {observation}\n"
            f"Last Error: {last_error or 'None'}\n\n"
            f"AVAILABLE TOOLS:\n"
            f"- run_command: Run shell command non-interactively (params: {{'command': str}})\n"
            f"- file_read: Read file contents (params: {{'path': str}})\n"
            f"- file_write: Write/overwrite file (params: {{'path': str, 'content': str}})\n"
            f"- file_edit: Resilient fuzzy patch (params: {{'path': str, 'target': str, 'replacement': str}})\n"
            f"- file_list: List files in workspace (params: {{'recursive': bool}})\n"
            f"- file_search: Regex search file contents (params: {{'pattern': str}})\n"
            f"- verify_test: Run tests/syntax check (params: {{'command': str or 'test_file': str}})\n"
            f"- ast_inspect: Extract AST classes and methods (params: {{'path': str}})\n"
            f"- update_plan: Mutate execution plan (params: {{'action': 'add_step'|'remove_step'|'replan', ...}})\n\n"
            f"COMPLETION INSTRUCTION:\n"
            f"When the primary goal is completely accomplished and verified, set 'is_finish': true, 'tool_name': null, and 'finish_summary': 'Detailed accomplishment description'.\n\n"
            f"Respond with a JSON object conforming strictly to:\n"
            f'{{"phase": "PLANNING|ACTING|REFLECTING|VERIFYING|MUTATION", "reasoning": "...", "tradeoffs": "...", "decision": "...", "tool_name": "run_command"|null, "tool_params": {{"command": "..."}}, "is_finish": false, "finish_summary": ""}}'
        )

        payload = {
            "contents": [{"parts": [{"text": prompt}]}],
            "generationConfig": {"temperature": 0.2, "responseMimeType": "application/json"},
        }

        try:
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={"Content-Type": "application/json"},
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                usage = data.get("usageMetadata", {})
                text = data["candidates"][0]["content"]["parts"][0]["text"]
                parsed = json.loads(text)
                sys.stderr.write(
                    f"[Gemini Step {step_number}] Tokens: {usage.get('totalTokenCount')} "
                    f"(Prompt: {usage.get('promptTokenCount')}, Candidates: {usage.get('candidatesTokenCount')})\n"
                    f"  Reasoning: {parsed.get('reasoning')}\n"
                    f"  Decision : {parsed.get('decision')} | Tool: {parsed.get('tool_name')}({parsed.get('tool_params')}) | Finish: {parsed.get('is_finish')}\n"
                )

                thought = ChainOfThoughtEngine.create_thought(
                    phase=parsed.get("phase", "ACTING"),
                    goal_analysis=config.goal,
                    observation=observation[:200],
                    decision=parsed.get("decision", ""),
                    tradeoffs=[parsed.get("tradeoffs", "")] if parsed.get("tradeoffs") else [],
                )
                return AgentDecision(
                    thought=thought,
                    tool_name=parsed.get("tool_name"),
                    tool_params=parsed.get("tool_params", {}),
                    is_finish=parsed.get("is_finish", False),
                    finish_summary=parsed.get("finish_summary", ""),
                    tokens_used=usage.get("totalTokenCount"),
                )
        except Exception as e:
            # On any network or API error, fallback to resilient offline heuristic provider
            sys.stderr.write(f"[GeminiProvider Warning: {e}]\n")
            return self.fallback.decide_next_step(config, plan, step_number, observation, last_error, workspace_files)


class OpenAIProvider(BaseProvider):
    """Zero-dependency HTTP client for OpenAI Compatible API endpoints."""

    def __init__(self, api_key: Optional[str] = None, model: str = "gpt-4o") -> None:
        self.api_key = api_key or os.environ.get("OPENAI_API_KEY", "")
        self.model = model
        self.fallback = HeuristicAutonomousProvider()

    def decide_next_step(
        self,
        config: BatchAgentConfig,
        plan: ExecutionPlan,
        step_number: int,
        observation: str,
        last_error: Optional[str] = None,
        workspace_files: Optional[List[str]] = None,
    ) -> AgentDecision:
        if not self.api_key:
            return self.fallback.decide_next_step(config, plan, step_number, observation, last_error, workspace_files)

        url = "https://api.openai.com/v1/chat/completions"
        system_msg = (
            "You are YoYo, an autonomous AI operating in a NON-INTERACTIVE BATCH OS.\n"
            "The PRIMARY GOAL is your overriding priority. You may change the plan and use 'update_plan' whenever necessary.\n"
            "Respond ONLY with valid JSON conforming to:\n"
            '{"phase": "PLANNING|ACTING|REFLECTING|VERIFYING|MUTATION", "reasoning": "...", "tradeoffs": "...", "decision": "...", "tool_name": "...", "tool_params": {}, "is_finish": false, "finish_summary": ""}'
        )
        user_msg = (
            f"PRIMARY GOAL (TOP PRIORITY): {config.goal}\n"
            f"Plan Status:\n{plan.format_summary()}\n"
            f"Associated Files: {config.associated_files}\n"
            f"Step: {step_number}\n"
            f"Observation: {observation}\n"
            f"Last Error: {last_error or 'None'}\n"
        )
        payload = {
            "model": self.model,
            "messages": [
                {"role": "system", "content": system_msg},
                {"role": "user", "content": user_msg},
            ],
            "response_format": {"type": "json_object"},
            "temperature": 0.2,
        }

        try:
            req = urllib.request.Request(
                url,
                data=json.dumps(payload).encode("utf-8"),
                headers={
                    "Content-Type": "application/json",
                    "Authorization": f"Bearer {self.api_key}",
                },
                method="POST",
            )
            with urllib.request.urlopen(req, timeout=30) as resp:
                data = json.loads(resp.read().decode("utf-8"))
                content = data["choices"][0]["message"]["content"]
                parsed = json.loads(content)

                thought = ChainOfThoughtEngine.create_thought(
                    phase=parsed.get("phase", "ACTING"),
                    goal_analysis=config.goal,
                    observation=observation[:200],
                    decision=parsed.get("decision", ""),
                    tradeoffs=[parsed.get("tradeoffs", "")] if parsed.get("tradeoffs") else [],
                )
                return AgentDecision(
                    thought=thought,
                    tool_name=parsed.get("tool_name"),
                    tool_params=parsed.get("tool_params", {}),
                    is_finish=parsed.get("is_finish", False),
                    finish_summary=parsed.get("finish_summary", ""),
                    tokens_used=usage.get("totalTokenCount"),
                )
        except Exception:
            return self.fallback.decide_next_step(config, plan, step_number, observation, last_error, workspace_files)


